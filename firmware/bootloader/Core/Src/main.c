/* GET_INFO diagnostic level 1 only; this check never authorizes a jump. */
static uint32_t Boot_AppVectorsSane(uint32_t msp, uint32_t reset_vector)
{
  uint32_t entry = reset_vector & ~1UL;

  /* Initial descending stack may point one byte past the RAM address range. */
  if ((msp <= APP_RAM_BASE) || (msp > APP_RAM_END_EXCLUSIVE) ||
      ((msp & 7UL) != 0UL))
  {
    return 0U;
  }

  if (((reset_vector & 1UL) == 0UL) ||
      (entry < (APP_BASE_ADDRESS + 8UL)) || (entry >= APP_END_EXCLUSIVE))
  {
    return 0U;
  }

  return 1U;
}

/* Called in the main loop, after CRC/version/length validation. */
static void Boot_OnFrame(const ProtocolFrame *request, void *context)
{
  (void)context;
  ProtocolFrame response;
  uint8_t wire[PROTOCOL_MAX_FRAME];
  uint32_t msp = *(const volatile uint32_t *)APP_BASE_ADDRESS;
  uint32_t reset = *(const volatile uint32_t *)(APP_BASE_ADDRESS + 4UL);
  BootCommands_Handle(&boot_commands, request,
                      (uint8_t)Boot_AppVectorsSane(msp, reset), &response);
  size_t length = Protocol_Encode(&response, wire, sizeof(wire));
  if (length == 0U) Error_Handler();
  /* A transport failure leaves the cached reply available for host retry. */
  (void)HAL_UART_Transmit(&huart2, wire, (uint16_t)length, 100U);
}

/* GCC/AAPCS: r0 = application MSP, r1 = Thumb reset vector.
 * No C statements or stack access are allowed in this naked tail routine.
 * PRIMASK stays set; the application explicitly enables IRQs before HAL_Init.
 */
__attribute__((naked, noreturn, noinline))
static void Boot_BranchToReset(uint32_t msp __attribute__((unused)),
                               uint32_t reset_vector __attribute__((unused)))
{
  __asm volatile (
      "movs r2, #0\n"
      "msr control, r2\n"
      "isb\n"
      "msr basepri, r2\n"
      "msr faultmask, r2\n"
      "msr psp, r2\n"
      "mvn lr, #0\n"
      "msr msp, r0\n"
      "dsb\n"
      "isb\n"
      "bx r1\n"
  );
}

/* Called only from privileged Thread mode in main(), never from an ISR. */
__attribute__((noreturn))
static void Boot_JumpToApp(uint32_t msp, uint32_t reset_vector)
{
  if ((__get_IPSR() != 0U) || ((__get_CONTROL() & 3U) != 0U))
  {
    Error_Handler();
  }

  /* Deinitialize USART before transferring ownership to the application. */
  if (HAL_UART_DeInit(&huart2) != HAL_OK)
  {
    Error_Handler();
  }
  /* Keep SysTick/IRQs running until HAL clock timeout handling is finished. */
  if (HAL_RCC_DeInit() != HAL_OK)
  {
    Error_Handler();
  }

  __disable_irq();
  SysTick->CTRL = 0U;
  SysTick->LOAD = 0U;
  SysTick->VAL = 0U;

  for (uint32_t bank = 0U; bank < (sizeof(NVIC->ICER) / sizeof(NVIC->ICER[0])); bank++)
  {
    NVIC->ICER[bank] = 0xFFFFFFFFUL;
    NVIC->ICPR[bank] = 0xFFFFFFFFUL;
  }
  EXTI->PR = EXTI->PR; /* W1C: clear any latched board-input edges. */
  SCB->ICSR = SCB_ICSR_PENDSTCLR_Msk | SCB_ICSR_PENDSVCLR_Msk;
  SCB->VTOR = APP_BASE_ADDRESS;
  __DSB();
  __ISB();

  Boot_BranchToReset(msp, reset_vector);
}
